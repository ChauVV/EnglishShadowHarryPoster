// Thông báo cho một mã lỗi: ưu tiên bản dịch theo mã; không có thì dùng `fallback` (thường là chữ máy chủ trả về), cuối cùng là câu chung.
export const errorText = (y, code, fallback) => y.err[code] ?? fallback ?? y.err.generic;
